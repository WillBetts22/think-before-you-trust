"""Aggregate results/kg_results_seeds_*.json -> results/summary.md and results/kg_auroc_by_checkpoint.png.
Every number quoted in README.md comes from summary.md."""
import glob
import json
import os

import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

HERE = os.path.dirname(os.path.abspath(__file__))
runs = []
for f in sorted(glob.glob(os.path.join(HERE, "results", "kg_results_seeds_*.json"))):
    runs += json.load(open(f))["runs"]
steps = sorted({r["step"] for r in runs})
seeds = sorted({r["seed"] for r in runs})


def agg(fn):
    out = {}
    for st in steps:
        vals = [fn(r) for r in runs if r["step"] == st]
        vals = [v for v in vals if v is not None and not (isinstance(v, float) and np.isnan(v))]
        out[st] = (float(np.mean(vals)), float(np.std(vals)), len(vals)) if vals else (float("nan"), float("nan"), 0)
    return out


def fmt(d, st, pct=False):
    m, s, n = d[st]
    return f"{m:.3f} ± {s:.3f}"


L = ["# Pilot B summary (generated by summarize.py)\n", f"Seeds: {seeds}. Checkpoints (training steps): {steps}. Values are mean ± sd across seeds.\n"]

rows = {
    "one-hop accuracy": lambda r: r["duality"]["fwd_acc"],
    "seen 2-hop: direct error": lambda r: r["composition"]["direct_error_rate"],
    "seen 2-hop: stepwise (Kleisli) error": lambda r: r["composition"]["stepwise_error_rate"],
    "seen 2-hop: compositionality gap (direct wrong | both hops right)": lambda r: r["composition"]["compositionality_gap"],
    "seen 2-hop: mean delta_comp (exact)": lambda r: r["composition"]["mean_delta_exact"],
    "held-out 2-hop: direct error": lambda r: r["composition_heldout"]["direct_error_rate"],
    "held-out 2-hop: stepwise (Kleisli) error": lambda r: r["composition_heldout"]["stepwise_error_rate"],
    "held-out 2-hop: mean delta_comp (exact)": lambda r: r["composition_heldout"]["mean_delta_exact"],
}
L.append("## Accuracy and composition\n")
L.append("| metric | " + " | ".join(f"step {s}" for s in steps) + " |")
L.append("|---|" + "---|" * len(steps))
for name, fn in rows.items():
    d = agg(fn)
    L.append(f"| {name} | " + " | ".join(fmt(d, s) for s in steps) + " |")

L.append("\n## E1: single-signal AUROC for 'direct answer is wrong' (seen 2-hop facts)\n")
feats = ["neg_conf_direct", "entropy_direct", "neg_conf_hop1", "neg_conf_hop2", "delta_comp_exact", "delta_comp_N3", "delta_comp_N10", "selfcons_3N_N3"]
L.append("| signal | " + " | ".join(f"step {s}" for s in steps) + " |")
L.append("|---|" + "---|" * len(steps))
for f in feats:
    d = agg(lambda r, f=f: r["composition"]["single_auroc"][f])
    L.append(f"| {f} | " + " | ".join(fmt(d, s) for s in steps) + " |")

L.append("\n## E1: H1-style incremental value (5-fold out-of-fold logistic regression; per-seed bootstrap CI)\n")
L.append("Baseline = direct confidence, direct entropy, hop-1 and hop-2 confidence. `exact`: add exact delta_comp. `N3 vs SC`: baseline + self-consistency from 9 samples, then add the N=3 sampled delta_comp (Will's estimator).\n")
L.append("| seed | step | AUROC base | + delta exact | gain [95% CI] | AUROC base+SC | + delta N3 | gain [95% CI] |")
L.append("|---|---|---|---|---|---|---|---|")
for r in sorted(runs, key=lambda r: (r["seed"], r["step"])):
    a, b = r["composition"]["h1_exact"], r["composition"]["h1_N3_vs_selfcons"]
    def g(x):
        return ("n/a",) * 3 if x is None else (f"{x['auc_base']:.3f}", f"{x['auc_aug']:.3f}", f"{x['gain']:+.3f} [{x['ci95'][0]:+.3f}, {x['ci95'][1]:+.3f}]")
    L.append(f"| {r['seed']} | {r['step']} | " + " | ".join(g(a)) + " | " + " | ".join(g(b)) + " |")

L.append("\n## E1b: consistent-but-wrong (seen 2-hop)\n")
L.append("| metric | " + " | ".join(f"step {s}" for s in steps) + " |")
L.append("|---|" + "---|" * len(steps))
for name, fn in {"fraction of queries whose routes agree (delta<0.1)": lambda r: r["composition"]["frac_agreeing"],
                 "error rate among agreeing queries": lambda r: r["composition"]["frac_wrong_among_agreeing"]}.items():
    d = agg(fn)
    L.append(f"| {name} | " + " | ".join(fmt(d, s) for s in steps) + " |")

L.append("\n## E2: duality (reversal)\n")
L.append("| metric | " + " | ".join(f"step {s}" for s in steps) + " |")
L.append("|---|" + "---|" * len(steps))
dk = ["inv_acc_trained_pairs", "inv_acc_untrained_pairs (reversal curse)", "mean_roundtrip_trained", "mean_roundtrip_untrained",
      "auroc_fwd_error_neg_conf_trained", "auroc_fwd_error_one_minus_roundtrip_trained",
      "auroc_fwd_error_neg_conf_untrained", "auroc_fwd_error_one_minus_roundtrip_untrained"]
for k in dk:
    d = agg(lambda r, k=k: r["duality"][k])
    L.append(f"| {k} | " + " | ".join(fmt(d, s) for s in steps) + " |")
L.append(f"\nChance accuracy = {runs[0]['duality']['chance']:.4f}.\n")
L.append("Round-trip H1 (baseline = forward confidence + entropy; add 1 − round-trip), reverse-trained pairs:\n")
L.append("| seed | step | AUROC base | + round-trip | gain [95% CI] |")
L.append("|---|---|---|---|---|")
for r in sorted(runs, key=lambda r: (r["seed"], r["step"])):
    x = r["duality"]["h1_roundtrip_trained"]
    if x is None:
        L.append(f"| {r['seed']} | {r['step']} | n/a | n/a | n/a |")
    else:
        L.append(f"| {r['seed']} | {r['step']} | {x['auc_base']:.3f} | {x['auc_aug']:.3f} | {x['gain']:+.3f} [{x['ci95'][0]:+.3f}, {x['ci95'][1]:+.3f}] |")

L.append("\n## E3: linear-relational functor (relations as ridge-fit affine maps on entity embeddings)\n")
for space in ["unembedding", "input_embedding"]:
    L.append(f"\n**{space}**\n")
    L.append("| metric | " + " | ".join(f"step {s}" for s in steps) + " |")
    L.append("|---|" + "---|" * len(steps))
    for k in ["one_hop_faithfulness_mean", "functoriality_defect_mean", "null_defect_mean",
              "composed_map_nn_acc_vs_model_2hop", "direct_2hop_map_nn_acc", "null_composed_nn_acc"]:
        d = agg(lambda r, k=k, space=space: r["linear_functor"][space][k])
        L.append(f"| {k} | " + " | ".join(fmt(d, s) for s in steps) + " |")
open(os.path.join(HERE, "results", "summary.md"), "w").write("\n".join(L) + "\n")

# figure: AUROC by checkpoint for the main signals + direct error
fig, axes = plt.subplots(1, 2, figsize=(11, 4))
series = [("neg_conf_direct", "direct confidence (reversed)", "#2a78d6", "o"),
          ("entropy_direct", "direct entropy", "#eb6834", "s"),
          ("delta_comp_exact", "delta_comp (exact Kleisli)", "#1baf7a", "^"),
          ("delta_comp_N3", "delta_comp (N=3 samples)", "#eda100", "v"),
          ("selfcons_3N_N3", "self-consistency (9 samples)", "#e87ba4", "D")]
for key, lab, col, mk in series:
    d = agg(lambda r, key=key: r["composition"]["single_auroc"][key])
    m = [d[s][0] for s in steps]; sd = [d[s][1] for s in steps]
    axes[0].errorbar(steps, m, yerr=sd, color=col, marker=mk, lw=2, ms=6, capsize=3, label=lab)
axes[0].axhline(0.5, color="#8a8a85", lw=1, ls="--")
axes[0].set_xscale("log"); axes[0].set_xlabel("training steps"); axes[0].set_ylabel("AUROC for wrong direct answer")
axes[0].set_title("E1: error-detection signals (seen 2-hop facts)", fontsize=10)
axes[0].legend(fontsize=8, frameon=False)
for key, lab, col, mk in [("seen 2-hop: direct error", "seen 2-hop, direct", "#2a78d6", "o"),
                          ("seen 2-hop: stepwise (Kleisli) error", "seen 2-hop, stepwise", "#eb6834", "s"),
                          ("held-out 2-hop: direct error", "held-out 2-hop, direct", "#1baf7a", "^"),
                          ("held-out 2-hop: stepwise (Kleisli) error", "held-out 2-hop, stepwise", "#eda100", "v")]:
    d = agg(rows[key]); m = [d[s][0] for s in steps]
    axes[1].plot(steps, m, color=col, marker=mk, lw=2, ms=6, label=lab)
axes[1].set_xscale("log"); axes[1].set_xlabel("training steps"); axes[1].set_ylabel("error rate")
axes[1].set_title("Direct vs stepwise error (held-out = never-seen compositions)", fontsize=10)
axes[1].legend(fontsize=8, frameon=False)
for ax in axes:
    ax.grid(alpha=0.25)
    for s in ["top", "right"]:
        ax.spines[s].set_visible(False)
fig.suptitle(f"Pilot B: tiny transformer on a synthetic knowledge graph ({len(seeds)} seeds; mean ± sd)", fontsize=10)
fig.tight_layout()
fig.savefig(os.path.join(HERE, "results", "kg_auroc_by_checkpoint.png"), dpi=130)
print("\n".join(L))
