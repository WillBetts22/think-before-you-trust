"""Turn results/sheaf_dag_results.json into results/summary.md (all numbers quoted in the README come from here)."""
import json, os
HERE = os.path.dirname(os.path.abspath(__file__))
r = json.load(open(os.path.join(HERE, "results", "sheaf_dag_results.json")))
L = ["# Pilot A summary (generated by summarize.py)\n"]
cols = ["Random", "Dependency-aware (repo)", "D only (structure)", "Conf x D", "Sheaf-tree x D (chain-only)",
        "Sheaf-DAG x D", "Sheaf-DAG+Conf x D", "Sheaf edge->upstream x D", "Naive incident energy x D", "Truth-greedy (ceiling)"]
L.append("## Reliability at budget 20 (mean over %d DAGs)\n" % r["grid"][0]["n_trials"])
L.append("| conf model | a (fabrication/noise) | q_consistent | extra-edge p | " + " | ".join(cols) + " |")
L.append("|" + "---|" * (4 + len(cols)))
for g in r["grid"]:
    c = g["config"]
    L.append(f"| {'overconfident' if c['overconfident'] else 'default'} | {c['a']} | {c['q_consistent']} | {c['extra_edge_prob']} | "
             + " | ".join(f"{g['reliability_mean'][k]:.3f}" for k in cols) + " |")
L.append("\n## Sheaf-DAG x D minus comparator (paired bootstrap 95% CI over DAGs), budget 20\n")
comp = ["Sheaf-tree x D (chain-only)", "D only (structure)", "Conf x D", "Dependency-aware (repo)"]
L.append("| conf | a | q | p | " + " | ".join(comp) + " |")
L.append("|" + "---|" * (4 + len(comp)))
for g in r["grid"]:
    c = g["config"]; d = g["sheafDAGxD_minus_other"]
    L.append(f"| {'over' if c['overconfident'] else 'default'} | {c['a']} | {c['q_consistent']} | {c['extra_edge_prob']} | "
             + " | ".join(f"{d[k]['mean']:+.3f} [{d[k]['ci95'][0]:+.3f}, {d[k]['ci95'][1]:+.3f}]" for k in comp) + " |")
L.append("\n## Node-level AUROC for 'claim is false' (pooled over DAGs)\n")
L.append("Columns: all false claims; and each false-claim kind vs true claims only.\n")
L.append("| conf | a | q | p | score | all false | originating | propagated, consistent | propagated, fresh |")
L.append("|---|---|---|---|---|---|---|---|---|")
for g in r["grid"]:
    c = g["config"]
    for s, v in g["node_auroc"].items():
        L.append(f"| {'over' if c['overconfident'] else 'default'} | {c['a']} | {c['q_consistent']} | {c['extra_edge_prob']} | {s} | "
                 + " | ".join(f"{v.get(k, float('nan')):.3f}" for k in ["all_false", "originating", "propagated_consistent", "propagated_fresh"]) + " |")
L.append("\n## Budget sweep at base config (a=2, q=0.9, p=0.15)\n")
for key, sw in r["budget_sweep_base"].items():
    L.append(f"\n**{key}**\n")
    L.append("| budget | " + " | ".join(cols) + " |")
    L.append("|" + "---|" * (1 + len(cols)))
    for b in sorted(sw, key=int):
        L.append(f"| {b} | " + " | ".join(f"{sw[b][k]:.3f}" for k in cols) + " |")
st = r["grid"][0]["dag_stats"]
L.append(f"\nDAG stats (base config): mean nodes {st['mean_nodes']:.1f}, mean false {st['mean_false']:.1f}, mean multi-parent nodes {st['mean_multi_parent_nodes']:.1f}.")
open(os.path.join(HERE, "results", "summary.md"), "w").write("\n".join(L) + "\n")
print("\n".join(L))
