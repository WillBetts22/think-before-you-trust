#!/usr/bin/env python3
"""
daily_job.py — chip away at the pilot a little each day until it's finished.

Each run:
    1. builds the pilot set (Stage A) if it doesn't exist yet
    2. runs Stage B, then Stage C, until today's budget runs out — either
       DAILY_MAX_API_CALLS (our cap) or the provider's daily quota
    3. once B and C both complete, runs Stages D and E, writes outputs/DONE,
       and sends a macOS notification; later runs then do nothing

Nothing is lost when a day's budget runs out: every call is cached, so the
next run replays finished work from disk for free and continues where it
stopped. Progress is appended to outputs/daily_log.txt.

Edits to outputs/audit.csv (include=0) take effect from the next run.

Scheduled by launchd (see run_daily.sh and the plist in README.md), or run by hand:
    DAILY_MAX_API_CALLS=500 python3 daily_job.py
"""

from __future__ import annotations

import re
import subprocess
import sys
from datetime import datetime

import config

OUT = config.OUTPUT_DIR
LOG = OUT / "daily_log.txt"
EXIT_BUDGET = 75
STATUS = config.PROJECT_DIR / "STATUS.md"
STATUS_HEADER = "<!-- runs: newest first; generated by daily_job.py -->"

# filled in as the run goes, then written to STATUS.md
run = {"stage": "-", "outcome": "-", "progress": "-", "new_calls": 0}


def log(msg: str) -> None:
    line = f"[{datetime.now():%Y-%m-%d %H:%M}] {msg}"
    print(line, flush=True)
    OUT.mkdir(parents=True, exist_ok=True)
    with open(LOG, "a") as f:
        f.write(line + "\n")


def stage(script: str) -> int:
    log(f"running {script}")
    proc = subprocess.run([sys.executable, script], cwd=config.PROJECT_DIR,
                          capture_output=True, text=True)
    tail = (proc.stdout + proc.stderr).strip().splitlines()[-3:]
    for line in tail:
        log(f"  {line}")
    run["stage"] = script
    # 03 replays cached questions each run, so its highest "[i/N]" line is
    # the number of questions finished so far
    done = re.findall(r"\[(\d+)/(\d+)\]", proc.stdout)
    if done:
        i, n = max(done, key=lambda m: int(m[0]))
        run["progress"] = f"{i}/{n} questions"
    return proc.returncode


def cached_calls() -> int:
    return sum(1 for _ in config.CACHE_DIR.rglob("*.json")) if config.CACHE_DIR.exists() else 0


def notify(msg: str) -> None:
    subprocess.run(["osascript", "-e", f'display notification "{msg}" with title "TBYT pilot"'],
                   capture_output=True)


def git(*args: str) -> subprocess.CompletedProcess:
    return subprocess.run(["git", *args], cwd=config.PROJECT_DIR, capture_output=True, text=True)


def write_status(started: datetime) -> None:
    """Prepend this run to STATUS.md, then commit and push that file alone."""
    row = (f"| {started:%Y-%m-%d} | {started:%H:%M}-{datetime.now():%H:%M} | {run['stage']} "
           f"| {run['outcome']} | {run['new_calls']} | {cached_calls()} | {run['progress']} |")
    old_rows = []
    if STATUS.exists():
        old_rows = [l for l in STATUS.read_text().splitlines() if re.match(r"\| \d{4}-", l)]
    STATUS.write_text("\n".join([
        "# TBYT pilot: daily run status", "",
        f"Last run: {started:%Y-%m-%d %H:%M}, {run['outcome']}. "
        "Written by `daily_job.py` after each scheduled run; details in outputs/daily_log.txt (not tracked).",
        "", STATUS_HEADER, "",
        "| date | time | stage | outcome | new API calls | total cached calls | progress |",
        "|---|---|---|---|---|---|---|",
        row, *old_rows, "",
    ]))

    branch = git("rev-parse", "--abbrev-ref", "HEAD").stdout.strip()
    if branch != "main":
        log(f"STATUS.md updated but not committed (on branch {branch!r}, not main)")
        return
    git("add", STATUS.name)
    # pathspec so nothing else you have staged ends up in this commit
    commit = git("commit", "-m", f"pilot status {started:%Y-%m-%d}: {run['outcome']}", "--", STATUS.name)
    if commit.returncode != 0:
        log(f"STATUS.md commit skipped: {(commit.stdout + commit.stderr).strip()[:200]}")
        return
    push = git("push", "origin", "main")
    if push.returncode != 0:
        log(f"STATUS.md committed but push failed (will go out with the next push): {push.stderr.strip()[:200]}")


def main() -> int:
    if (OUT / "DONE").exists():
        log("pilot already finished — nothing to do (remove the launchd job: see README)")
        run["outcome"] = "already finished"
        return 0

    before = cached_calls()
    if not (OUT / "tasks.jsonl").exists():
        if stage("01_build_pilot.py") != 0:
            log("Stage A failed")
            run["outcome"] = "Stage A failed"
            return 1

    for script, product in (("02_generate_original.py", "original.jsonl"),
                            ("03_run_probes.py", "probes.jsonl")):
        if (OUT / product).exists():
            continue
        code = stage(script)
        run["new_calls"] = cached_calls() - before
        if code == EXIT_BUDGET:
            log(f"budget used up for today; new API calls this run: {run['new_calls']}")
            run["outcome"] = "daily limit hit, resumes tomorrow"
            return 0
        if code != 0:
            run["outcome"] = f"failed (exit {code})"
            log(f"{script} failed with exit code {code}; will retry next run")
            notify(f"{script} failed — see outputs/daily_log.txt")
            return 1

    for script in ("04_label.py", "05_analyze.py"):
        if stage(script) != 0:
            log(f"{script} failed")
            run["outcome"] = "failed"
            return 1
    (OUT / "DONE").write_text(datetime.now().isoformat())
    log(f"pilot finished; results in {OUT / 'results.json'}")
    notify("Pilot finished — results in outputs/results.json")
    run["outcome"] = "pilot finished"
    return 0


if __name__ == "__main__":
    started = datetime.now()
    try:
        code = main()
    except Exception as e:
        run["outcome"] = f"crashed: {type(e).__name__}"
        raise
    finally:
        try:
            write_status(started)
        except Exception as e:
            log(f"could not write STATUS.md: {e}")
    sys.exit(code)
